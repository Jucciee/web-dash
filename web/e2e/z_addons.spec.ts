import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('author, test, export and import API addons with private credentials and home widgets', async ({ page }) => {
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const checks = async () => (await (await page.request.get('http://127.0.0.1:18082/__addon_checks')).json()).checks
  await page.goto('/')
  await expect(page.getByLabel('관리자 아이디')).toBeVisible()
  if (await page.getByRole('heading', { name: '관리자 설정', exact: true }).isVisible()) {
    await page.getByLabel('초기 설정 토큰').fill('playwright-test-only-setup-token-32-characters')
    await page.getByLabel('관리자 아이디').fill('browser-admin')
    await page.getByLabel('비밀번호', { exact: true }).fill('correct horse battery staple')
    await page.getByRole('button', { name: '관리자 계정 만들기' }).click()
  } else {
    await page.getByLabel('관리자 아이디').fill('browser-admin')
    await page.getByLabel('비밀번호', { exact: true }).fill('correct horse battery staple')
    await page.getByRole('button', { name: '로그인', exact: true }).click()
  }
  await expect(page.locator('.home-dashboard')).toBeVisible()
  await page.goto('/settings/addons')
  await page.getByRole('button', { name: '새 애드온', exact: true }).click()
  await page.getByLabel('애드온 이름', { exact: true }).fill('테스트 API')
  await page.getByLabel('API 주소', { exact: true }).fill('http://127.0.0.1:18082/addon/status')
  await page.getByRole('button', { name: '서버 주소를 입력 항목으로 분리' }).click()
  await page.getByRole('button', { name: 'Bearer 토큰', exact: true }).click()
  await page.getByRole('button', { name: '쿠키', exact: true }).click()
  await page.getByLabel(/^API 토큰/).fill('e2e-addon-token')
  await page.getByLabel(/^Cookie 값/).fill('session=e2e-addon-cookie')
  await page.getByLabel('애드온 갱신 간격').selectOption('0')
  await page.getByRole('button', { name: '연결 테스트', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^연결 성공 · HTTP 200/ })).toBeVisible()
  await expect(page.getByRole('button', { name: '/echo 값 추가', exact: true })).toContainText('••••')
  await page.getByRole('button', { name: '/metrics/active 값 추가', exact: true }).click()
  await page.getByLabel('표시 이름 1', { exact: true }).fill('진행 중')
  await page.getByText('단위·계산 설정 1', { exact: true }).click()
  await page.getByLabel('단위 1', { exact: true }).fill('개')
  await page.getByRole('button', { name: '/metrics/load 값 추가', exact: true }).click()
  await page.getByLabel('표시 이름 2', { exact: true }).fill('부하')
  await page.getByLabel('표시 형식 2').selectOption('percent')
  await page.getByText('단위·계산 설정 2', { exact: true }).click()
  await page.getByLabel('배수 2', { exact: true }).fill('100')
  await page.getByLabel('소수 자릿수 2', { exact: true }).fill('1')
  await page.getByRole('button', { name: '연결 테스트', exact: true }).click()
  await expect(page.locator('.addon-metric').first()).toContainText('0개')
  await expect(page.locator('.addon-metric').nth(1)).toContainText('25.0%')
  for (const width of [320, 375, 414, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.screenshot({ path: 'test-results/addon-editor-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '애드온 설치', exact: true }).click()
  await expect(page.getByRole('region', { name: '테스트 API 설치 설정' })).toBeVisible()
  const list = (await (await page.request.get('/api/v1/addons')).json()).data
  expect(JSON.stringify(list)).not.toContain('e2e-addon-token')
  expect(JSON.stringify(list)).not.toContain('e2e-addon-cookie')
  expect(list[0].configuredSecrets).toEqual(['token', 'cookie'])
  await page.goto('/')
  const widget = page.getByRole('region', { name: '테스트 API 애드온', exact: true })
  await expect(widget).toContainText('진행 중')
  await expect(widget).toContainText('0개')
  await expect(widget).toContainText('25.0%')
  await page.setViewportSize({ width: 375, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/addon-home-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/settings/addons')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '테스트 API JSON 내보내기', exact: true }).click()
  const download = await downloadEvent
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(exported.schemaVersion).toBe(1)
  expect(exported.request.url).toBe('{{baseUrl}}/addon/status')
  expect(JSON.stringify(exported)).not.toContain('18082')
  expect(JSON.stringify(exported)).not.toContain('e2e-addon-token')
  expect(exported).not.toHaveProperty('values')
  expect(exported).not.toHaveProperty('secrets')

  const beforeImport = await checks()
  await page.getByLabel('애드온 JSON 파일', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...exported, request: { ...exported.request, headers: null } })) })
  await expect(page.getByText('요청 헤더는 name과 value로 구성한 배열이어야 합니다.')).toBeVisible()
  await expect(page.getByRole('button', { name: '새 애드온', exact: true })).toBeVisible()
  const shared = { ...exported, name: '가져온 API', display: 'list', fields: [...exported.fields, { label: '상태', path: '/status', format: 'text', unit: '', scale: 1, decimals: 0, valueMap: { healthy: '정상' } }] }
  await page.getByLabel('애드온 JSON 파일', { exact: true }).setInputFiles({ name: 'shared.web-dash.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(shared)) })
  await expect(page.getByLabel(/^API 토큰/)).toHaveValue('')
  await expect(page.getByLabel(/^Cookie 값/)).toHaveValue('')
  expect(await checks()).toBe(beforeImport)
  await page.getByLabel('홈에서 사용').uncheck()
  await page.getByRole('button', { name: '애드온 설치', exact: true }).click()
  const imported = page.getByRole('region', { name: '가져온 API 설치 설정' })
  await expect(imported).toContainText('비활성화')
  expect(await checks()).toBe(beforeImport)
  await imported.getByRole('button', { name: '편집', exact: true }).click()
  await page.getByLabel('서버 주소', { exact: true }).fill('http://127.0.0.1:18082')
  await page.getByLabel(/^API 토큰/).fill('wrong-token')
  await page.getByLabel(/^Cookie 값/).fill('session=e2e-addon-cookie')
  await page.getByRole('button', { name: '연결 테스트', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^연결 실패 · HTTP 401/ })).toBeVisible()
  await page.getByLabel(/^API 토큰/).fill('e2e-addon-token')
  await page.getByLabel('홈에서 사용').check()
  await page.getByRole('button', { name: 'JSON 설정', exact: true }).click()
  const source = page.getByLabel('애드온 정의 JSON', { exact: true })
  const changed = JSON.parse(await source.inputValue())
  changed.fields[2].valueMap.healthy = '정상 연결'
  await source.fill(JSON.stringify(changed, null, 2))
  await expect(page.getByRole('button', { name: '연결 테스트', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '간편 편집', exact: true }).click()
  await page.getByRole('button', { name: '연결 테스트', exact: true }).click()
  await expect(page.locator('.addon-metric').nth(2)).toContainText('정상 연결')
  await page.getByRole('button', { name: '애드온 저장', exact: true }).click()
  await expect(imported).toContainText('사용 중')
  await page.getByRole('button', { name: '가져온 API 위로 이동', exact: true }).click()
  await expect(page.locator('[aria-label$="설치 설정"]').first()).toHaveAttribute('aria-label', '가져온 API 설치 설정')
  await page.getByRole('region', { name: '테스트 API 설치 설정' }).getByRole('button', { name: '편집', exact: true }).click()
  await expect(page.getByLabel(/^API 토큰/)).toHaveValue('')
  await expect(page.getByLabel(/^API 토큰/)).toHaveAttribute('placeholder', '저장한 값 사용 · 새 값 입력 시 교체')
  await page.getByLabel('애드온 이름', { exact: true }).fill('수정 API')
  await page.getByRole('button', { name: '애드온 저장', exact: true }).click()
  await expect(page.getByRole('region', { name: '수정 API 설치 설정' })).toBeVisible()
  await page.goto('/')
  await expect(page.locator('.addon-widget')).toHaveCount(2)
  await expect(page.locator('.addon-widget').first()).toHaveAttribute('aria-label', '가져온 API 애드온')
  await expect(page.locator('.addon-widget').first()).toContainText('정상 연결')
  await expect(page.getByRole('region', { name: '수정 API 애드온' })).toContainText('25.0%')
  for (const width of [320, 375, 414, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.screenshot({ path: 'test-results/addon-home-desktop.png', fullPage: true })
  await page.reload()
  await expect(page.locator('.addon-widget').first()).toHaveAttribute('aria-label', '가져온 API 애드온')
  await expect(page.getByRole('region', { name: '수정 API 애드온' })).toContainText('25.0%')
  const beforePreview = await checks()
  await page.goto('/settings')
  const preview = page.getByRole('complementary', { name: '홈 화면 미리보기' })
  await expect(preview.locator('.addon-widget')).toHaveCount(2)
  await expect(preview.locator('.addon-metric').first()).toContainText('—')
  await page.getByLabel('모서리').selectOption('round')
  await expect(preview.locator('[data-appearance]')).toHaveAttribute('data-radius', 'round')
  expect(await checks()).toBe(beforePreview)
  await page.goto('/settings/addons')
  await page.getByRole('button', { name: '수정 API 비활성화', exact: true }).click()
  await expect(page.getByRole('region', { name: '수정 API 설치 설정' })).toContainText('비활성화')
  await page.getByRole('button', { name: '가져온 API 삭제', exact: true }).click()
  await page.getByRole('button', { name: '애드온 삭제', exact: true }).click()
  await expect(page.getByRole('region', { name: '가져온 API 설치 설정' })).toHaveCount(0)
  await page.goto('/')
  await expect(page.locator('.addon-widget')).toHaveCount(0)
  expect(errors).toEqual([])
})
