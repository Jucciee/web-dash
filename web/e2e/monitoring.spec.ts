import { expect, test } from '@playwright/test'

test('Docker and host readings, scoped preview, customization persistence and recovery under production CSP', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('Failed to load resource')) errors.push(message.text()) })
  await page.goto('http://127.0.0.1:18080/')
  await expect(page.getByLabel('관리자 아이디')).toBeVisible()
  const setup = page.getByRole('heading', { name: '관리자 설정', exact: true })
  if (await setup.isVisible()) {
    await page.getByLabel('초기 설정 토큰').fill('playwright-test-only-setup-token-32-characters')
    await page.getByLabel('관리자 아이디').fill('browser-admin')
    await page.getByLabel('비밀번호', { exact: true }).fill('correct horse battery staple')
    await page.getByRole('button', { name: '관리자 계정 만들기' }).click()
  } else if (await page.getByLabel('관리자 아이디').isVisible()) {
    await page.getByLabel('관리자 아이디').fill('browser-admin')
    await page.getByLabel('비밀번호', { exact: true }).fill('correct horse battery staple')
    await page.getByRole('button', { name: '로그인', exact: true }).click()
  }
  await expect(page.locator('.host-widget')).toBeVisible()
  await expect(page.locator('.docker-widget')).toContainText('e2e-engine')
  await page.goto('http://127.0.0.1:18080/connections')
  await expect(page.getByRole('heading', { name: 'Docker 상태', exact: true })).toBeVisible()
  await expect(page.getByText('200 MiB', { exact: true }).first()).toBeVisible()
  await page.getByLabel('상태 필터').selectOption('unhealthy')
  await expect(page.getByText('unhealthy-worker', { exact: true })).toBeVisible()
  await expect(page.getByText('stopped-worker', { exact: true })).toHaveCount(0)
  await page.getByLabel('상태 필터').selectOption('stopped')
  await expect(page.getByText('stopped-worker', { exact: true })).toBeVisible()
  await expect(page.getByText('unhealthy-worker', { exact: true })).toHaveCount(0)
  await page.getByLabel('상태 필터').selectOption('all')
  for (const width of [320, 375, 414, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.screenshot({ path: 'test-results/docker-status-desktop.png', fullPage: true })
  await page.goto('http://127.0.0.1:18080/hosts')
  await expect(page.getByRole('meter', { name: '메모리 사용량' })).toBeVisible()
  await expect(page.getByText('web-dash 실행 호스트', { exact: false })).toBeVisible()
  await page.screenshot({ path: 'test-results/host-status-desktop.png', fullPage: true })

  await page.goto('http://127.0.0.1:18080/settings')
  const before = (await (await page.request.get('http://127.0.0.1:18080/api/v1/settings')).json()).data
  const originalTheme = await page.locator('html').getAttribute('data-theme')
  const preview = page.getByRole('complementary', { name: '홈 화면 미리보기' })
  const previewTheme = originalTheme === 'dark' ? 'light' : 'dark'
  await page.getByRole('combobox', { name: '테마', exact: true }).selectOption(previewTheme)
  await expect(preview.locator('[data-appearance]')).toHaveAttribute('data-theme', previewTheme)
  await expect(page.locator('html')).toHaveAttribute('data-theme', originalTheme!)
  await page.getByRole('button', { name: /^홈 랩/ }).click()
  await expect(preview.locator('[data-appearance]')).toHaveAttribute('data-theme', 'dark')
  await page.getByLabel('그룹 배치').selectOption('rows')
  await page.getByLabel('열 수').selectOption('6')
  await page.getByLabel('화면 폭').selectOption('full')
  await page.getByLabel('카드 모양').selectOption('tile')
  await page.getByLabel('모서리').selectOption('round')
  await page.getByRole('combobox', { name: '강조색', exact: true }).selectOption('custom')
  await page.getByLabel('사용자 강조색').fill('#4c9f70')
  await page.getByLabel('배경 이미지 업로드').setInputFiles({ name: 'wallpaper.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64') })
  await expect(preview.locator('[data-appearance]')).toHaveAttribute('data-background', 'image')
  await expect(preview.locator('[data-appearance]')).toHaveCSS('background-image', /backgrounds/)
  // Unsaved preview does not change the stored settings or apply arbitrary CSS.
  const stored = (await (await page.request.get('http://127.0.0.1:18080/api/v1/settings')).json()).data
  expect(stored).toEqual(before)
  await page.getByRole('button', { name: '표시 항목', exact: true }).click()
  await page.getByLabel('홈 제목', { exact: true }).fill('내 서버')
  await page.getByLabel('시계 표시').uncheck()
  await page.getByLabel('검색창 표시').uncheck()
  await page.getByLabel('링크 설명 표시').uncheck()
  await page.getByLabel('링크 주소 표시').check()
  await page.getByLabel('그룹 접기 허용').check()
  await page.getByRole('button', { name: '위젯', exact: true }).click()
  await page.getByLabel('위젯 순서').selectOption('docker')
  await page.getByLabel('상태 갱신 간격').selectOption('0')
  await page.getByRole('button', { name: '고급', exact: true }).click()
  await page.getByLabel('사용자 CSS', { exact: true }).fill('.service-card { border-radius: 23px; }')
  for (const width of [320, 375, 414, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.getByRole('button', { name: '변경 저장', exact: true }).click()
  await expect(page.getByText('설정을 저장했습니다.')).toBeVisible()
  await page.goto('http://127.0.0.1:18080/')
  await expect(page.getByRole('heading', { name: '내 서버', exact: true })).toBeVisible()
  await expect(page.getByLabel('링크 검색')).toHaveCount(0)
  await expect(page.locator('[data-appearance]')).toHaveAttribute('data-columns', '6')
  await expect(page.locator('.home-widgets > section').first()).toHaveClass(/docker-widget/)
  await expect(page.locator('[data-appearance]')).toHaveCSS('background-image', /backgrounds/)
  const firstGroup = page.locator('.service-group').first()
  if (await firstGroup.count()) {
    const toggle = firstGroup.getByRole('button')
    await toggle.click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(firstGroup.locator('.service-card').first()).toBeHidden()
    await toggle.click()
    await expect(firstGroup.locator('.service-card').first()).toBeVisible()
  }
  for (const width of [320, 375, 414, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.reload()
  await expect(page.getByRole('heading', { name: '내 서버', exact: true })).toBeVisible()
  // Even CSS that hides the home leaves the editor available.
  await page.goto('http://127.0.0.1:18080/settings')
  await page.getByRole('button', { name: '고급', exact: true }).click()
  await page.getByLabel('사용자 CSS', { exact: true }).fill('.home-dashboard { display: none; }')
  await page.getByRole('button', { name: '변경 저장', exact: true }).click()
  await expect(page.getByText('설정을 저장했습니다.')).toBeVisible()
  await page.goto('http://127.0.0.1:18080/')
  await expect(page.locator('.home-dashboard')).toBeHidden()
  await page.goto('http://127.0.0.1:18080/settings')
  await expect(page.getByRole('heading', { name: '설정', exact: true })).toBeVisible()
  await expect(page.locator('link[data-custom-css]')).toHaveCount(0)
  await page.getByRole('button', { name: /^기본/ }).click()
  await page.getByRole('button', { name: '고급', exact: true }).click()
  await page.getByRole('button', { name: 'CSS 지우기', exact: true }).click()
  await page.getByRole('button', { name: '표시 항목', exact: true }).click()
  await page.getByLabel('홈 제목', { exact: true }).fill('web-dash')
  await page.getByRole('button', { name: '변경 저장', exact: true }).click()
  await expect(page.getByText('설정을 저장했습니다.')).toBeVisible()
  await page.getByRole('button', { name: '화면', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/customization-settings-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})
